import os
import json

# Locate repository root directory (one level up from py/)
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GALLERY_DIR = os.path.join(BASE_DIR, "gallery")
OUTPUT_FILE = os.path.join(BASE_DIR, "js", "galleryphotos.local.js")

VALID_EXTENSIONS = (".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif", ".bmp")


def generate_gallery(gallery_dir=None, output_file=None):
    """Scan gallery_dir for images, build categorized structure, and write to output_file."""
    target_dir = gallery_dir or GALLERY_DIR
    target_output = output_file or OUTPUT_FILE

    # Ensure gallery directory exists
    os.makedirs(target_dir, exist_ok=True)
    os.makedirs(os.path.dirname(target_output), exist_ok=True)

    structure = {}

    for root, _, files in os.walk(target_dir):
        for file in files:
            if not file.lower().endswith(VALID_EXTENSIONS):
                continue

            full_path = os.path.join(root, file)

            # Get path relative to target_dir (gallery/)
            rel_path = os.path.relpath(full_path, target_dir)
            rel_path = rel_path.replace(os.sep, "/")

            # Determine category: top-level subfolder, or "root" if directly in gallery/
            parts = rel_path.split("/")
            if len(parts) > 1:
                category = parts[0]
            else:
                category = "root"

            web_path = f"gallery/{rel_path}"
            structure.setdefault(category, []).append(web_path)

    # Sort each category's images and sort category keys
    for category in structure:
        structure[category].sort()

    sorted_structure = dict(sorted(structure.items()))

    # Write output JS file with window and var declarations for runtime updates
    js_content = (
        "// Auto-generated by generate_gallery.py\n"
        "window.GALLERY_STRUCTURE = "
        + json.dumps(sorted_structure, indent=2)
        + ";\n"
        + "var GALLERY_STRUCTURE = window.GALLERY_STRUCTURE;\n"
    )

    with open(target_output, "w", encoding="utf-8") as f:
        f.write(js_content)

    total_images = sum(len(v) for v in sorted_structure.values())
    return {
        "ok": True,
        "total_images": total_images,
        "categories": list(sorted_structure.keys()),
        "structure": sorted_structure,
        "output_file": target_output,
    }


def main():
    res = generate_gallery()
    if res.get("ok"):
        print(
            f"Generated {res['output_file']} with {res['total_images']} images "
            f"across {len(res['categories'])} categories."
        )
    else:
        print(f"Failed to generate gallery: {res.get('error')}")


if __name__ == "__main__":
    main()